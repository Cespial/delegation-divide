"""Regenera el bloque «Headline» de README.md desde salidas/claims.jsonl.

Uso (desde la raíz del repo):  .venv/bin/python -I release/actualizar_readme.py [--check]
Reemplaza lo que haya entre <!-- headline:start --> y <!-- headline:end -->. Con --check no escribe: sale con 1 si el
README está desactualizado. Falla si falta un id o si alguna cifra es sintética o está pendiente («--»).
"""
from __future__ import annotations

import json
import re
import sys
from pathlib import Path

RAIZ = Path(__file__).resolve().parents[1]
README = RAIZ / "README.md"
CLAIMS = RAIZ / "salidas" / "claims.jsonl"
INI, FIN = "<!-- headline:start -->", "<!-- headline:end -->"


def cargar() -> dict:
    out = {}
    for l in CLAIMS.read_text(encoding="utf-8").splitlines():
        if l.strip():
            c = json.loads(l)
            out[c["id"]] = c
    return out


def bloque(C: dict) -> str:
    def v(i: str) -> float:
        if i not in C:
            raise KeyError(f"falta {i} en {CLAIMS}")
        c = C[i]
        if c.get("sintetico"):
            raise ValueError(f"{i} es sintético: no se publica")
        if not isinstance(c["valor"], (int, float)):
            raise ValueError(f"{i} no tiene valor numérico ({c['valor']!r})")
        return float(c["valor"])

    f1 = lambda i: f"{v(i):.1f}"
    f2 = lambda i: f"{v(i):.2f}"
    pval = v("h1.p")
    p_txt = "p < 0.001" if pval < 0.001 else f"p = {pval:.3f}"
    filas = [
        ("High income", "alto"), ("Upper-middle income", "medio_alto"),
        ("Lower-middle income", "medio_bajo"), ("Low income", "bajo"),
    ]
    tabla = "\n".join(
        f"| {nom} | {int(v(f'cobertura.ingreso.{c}.paises'))} | {f1(f'titular.ingreso.{c}.l2')} | {f1(f'titular.ingreso.{c}.l3')} |"
        for nom, c in filas
    )
    return f"""{INI}
<!-- generated by release/actualizar_readme.py from salidas/claims.jsonl; do not edit by hand -->
## Headline

**{f1('titular.global.l2')} % of task time in world employment is at least partly delegable to AI agents (L2+) in 2026
(95 % CI {f1('titular.global.l2.lo')}–{f1('titular.global.l2.hi')}); only {f1('titular.global.l3')} % can be handed over in full (L3,
95 % CI {f1('titular.global.l3.lo')}–{f1('titular.global.l3.hi')}).** {int(v('cobertura.tareas')):,} O\\*NET tasks, {int(v('cobertura.isco'))} ISCO-08 unit groups,
{int(v('cobertura.paises'))} countries, {v('cobertura.empleo_millones') / 1000:.2f} billion workers.

| Income group (World Bank FY2026) | Countries | L2+ (%) | L3 (%) |
|---|---:|---:|---:|
{tabla}

- **H1, the delegation divide (supported):** delegable employment rises with income — {f2('h1.pendiente')} percentage points
  per log point of GDP per capita (95 % CI {f2('h1.pendiente.lo')}–{f2('h1.pendiente.hi')}, {p_txt}, R² = {f2('h1.r2')},
  {int(v('h1.n'))} countries).
- **H4, task length (supported):** Full delegation peaks for tasks that take a human about twelve minutes
  (estimated peak: {f1('h4.pico.minutos')} minutes).
- Model agreement (Sonnet 5.5 vs Haiku 5.5): quadratic-weighted κ = {f2('agree.kappa.sonnet_haiku')}. A blind human rating of {int(v('n.humano'))} tasks
  (led by a coauthor with student raters, analysed as one rating) agrees with the model consensus at κ = {f2('agree.kappa.humano.modelo')};
  an agentic panel (Claude Opus 5.5 with web search, 1,500 tasks) agrees at κ = {f2('agree.kappa.panel.modelo')}.

Every number above has an id in [`salidas/claims.jsonl`](salidas/claims.jsonl) (`titular.*`, `h1.*`, `h4.pico.minutos`).
{FIN}"""


def main() -> int:
    nuevo_bloque = bloque(cargar())
    txt = README.read_text(encoding="utf-8")
    patron = re.compile(re.escape(INI) + r".*?" + re.escape(FIN), re.S)
    if not patron.search(txt):
        print(f"ERROR: README.md no tiene las marcas {INI} … {FIN}", file=sys.stderr)
        return 2
    nuevo = patron.sub(lambda _: nuevo_bloque, txt)
    if "--check" in sys.argv:
        if nuevo != txt:
            print("README.md desactualizado: corre release/actualizar_readme.py")
            return 1
        print("README.md al día")
        return 0
    README.write_text(nuevo, encoding="utf-8")
    print("README.md: bloque headline regenerado")
    return 0


if __name__ == "__main__":
    sys.exit(main())
